export const pemToDer = (pem: string): Uint8Array =>
  base64ToBytes(pem.replace(/-----[^-]+-----|\s/g, ""))

for (const [name, root] of Object.entries(TSA_ROOTS)) {
  if (bytesToHex(sha256(pemToDer(root.pem))) !== root.sha256) {
    throw new Error(`pinned ${name} root does not match its fingerprint`)
  }
}
