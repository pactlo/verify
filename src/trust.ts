// Ed25519 SubjectPublicKeyInfo: a fixed 12-byte header, then the 32-byte key.
const ED25519_SPKI_PREFIX = hexToBytes("302a300506032b6570032100")

export function rawEd25519Key(spkiBase64: string): Uint8Array {
  const spki = base64ToBytes(spkiBase64)
  if (spki.length !== 44 || !equalBytes(spki.subarray(0, 12), ED25519_SPKI_PREFIX)) {
    throw new Error("not an Ed25519 public key")
  }
  return spki.subarray(12)
}

// Strict RFC 8032 verification (as OpenSSL and AWS KMS do).
export function verifyBlockSignature(
  hash: Uint8Array,
  keyId: string,
  signature: Uint8Array,
  keys: Record<string, Pick<SigningKey, "publicKey">> = SIGNING_KEYS,
): boolean {
  const key = keys[keyId]
  if (!key || signature.length !== 64) return false
  try {
    return ed25519.verify(signature, signatureMessage(hash), rawEd25519Key(key.publicKey), {
      zip215: false,
    })
  } catch {
    return false
  }
}

